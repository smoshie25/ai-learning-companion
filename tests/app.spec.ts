  await expect(page.getByRole('dialog').getByText(/I know that generics/)).toBeVisible()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Learning Sessions', exact: true }).click()
  await page.getByRole('article').filter({ hasText: 'Understanding TypeScript generics' }).getByRole('button', { name: 'Review session & highlights' }).click()
