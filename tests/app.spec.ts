  await expect(page.getByRole('dialog').getByText(/I know that generics/)).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Mock Interviews', exact: true }).click()
  await screenshot('interview-setup')
  await page.getByRole('button', { name: 'Behavioral', exact: true }).click()
  await page.getByRole('button', { name: 'Start practice interview' }).click()
